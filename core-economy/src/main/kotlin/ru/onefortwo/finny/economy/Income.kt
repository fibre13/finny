package ru.onefortwo.finny.economy

/**
 * Источники игровой валюты. Баланс не меняется без указания источника
 * и суммы (ТЗ 2.5.4), поэтому любое начисление проходит через [IncomeSource].
 */
enum class IncomeSource(val amount: Coins) {
    /** Стартовый бюджет, начисляется один раз при создании профиля. */
    START_BUDGET(Coins(50)),

    /**
     * Карманные монеты в начале каждого периода, кроме первого.
     *
     * Величина подобрана так, чтобы выбор между обязательным, желаемым
     * и накоплениями оставался настоящим. При тридцати монетах доход
     * обгонял расходы примерно на двадцать пять монет в день: запас
     * рос быстрее, чем стоил весь каталог, и выбирать было уже не из
     * чего. При двадцати пяти ребёнок, который держит питомца довольным,
     * откладывает девять-тринадцать монет в день, а тот, кто копит
     * быстрее, видит, как падает радость питомца.
     */
    POCKET_MONEY(Coins(25)),

    /** Награда за верно выполненное задание. */
    TASK_CORRECT(Coins(10)),

    /** Награда за участие при ошибочном решении задания. */
    TASK_PARTIAL(Coins(5)),

    /** Награда за задание восстановления после неудачного периода. */
    RECOVERY_TASK(Coins(10)),
}

/** Факт начисления: что показать пользователю после изменения баланса. */
data class IncomeEvent(
    val source: IncomeSource,
    val amount: Coins,
    val balanceAfter: Coins,
)
