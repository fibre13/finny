package ru.onefortwo.finny.economy

/**
 * Выбранный уровень сложности заданий.
 *
 * Хранится в профиле и определяет, какие задания показываются ребёнку:
 * ТЗ 2.5.8 требует, чтобы сложность формулировок и вычислений
 * соответствовала возрасту 7–11 лет, а разница в устном счёте внутри
 * этого диапазона велика.
 *
 * Спрашивается именно сложность, а не возраст и не класс. Возраст —
 * сведение о ребёнке, и хранение его на устройстве само по себе не
 * делает его неперсональным; для подбора заданий достаточно выбора
 * «попроще или посложнее», и тогда приложение не собирает о ребёнке
 * ничего (ТЗ 3.2, 3.5).
 *
 * Тип объявлен в модуле экономики как общий словарь предметной области:
 * на него опираются и учебный контент, и слой хранения, которые оба
 * зависят от этого модуля и не зависят друг от друга.
 */
enum class Difficulty(val displayName: String, val hint: String) {
    /** Счёт в пределах двадцати, без деления. */
    SIMPLE("Попроще", "Числа небольшие, делить не нужно"),

    /** Двузначные числа и деление. */
    HARDER("Посложнее", "Числа побольше, встречается деление");

    companion object {
        /** Уровень по сохранённому имени; неизвестное значение даёт «Попроще». */
        fun ofName(name: String?): Difficulty =
            entries.firstOrNull { it.name == name } ?: SIMPLE
    }
}
